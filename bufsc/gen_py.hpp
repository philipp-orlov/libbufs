#pragma once

// The Python generator: <stem>_bufs.py for the messages of a schema. See gen_py.cpp.

#include <cctype>
#include <cmath>
#include <cstdlib>
#include <cstring>
#include <set>
#include <sstream>

#include "generators.hpp"

namespace bufsc {

class PyGenerator {
public:
    PyGenerator(const Schema& schema, const GenOptions& options) : schema_(schema), options_(options) {}
    virtual ~PyGenerator() = default;

    std::string run() {
        std::ostringstream body;
        for (const auto& e : schema_.enums)
            if (inMainFile(schema_, *e))
                emitEnum(body, *e);
        for (const auto& s : schema_.structs)
            if (inMainFile(schema_, *s))
                emitStruct(body, *s);
        for (const auto& t : schema_.tables)
            if (inMainFile(schema_, *t))
                emitTable(body, *t);
        bool services = false;
        for (const auto& s : schema_.services)
            if (inMainFile(schema_, *s)) {
                emitService(body, *s);
                services = true;
            }
        std::ostringstream out;
        out << "# Generated by " << options_.generator << " from " << stemOf(schema_.mainFile) << ".bufs. Do not edit.\n"
            << "# fmt: off\n"
            << "import struct as _struct\n"
            << "from enum import IntEnum as _IntEnum\n"
            << "from " << runtimeModule() << " import (Table, MessageBuilder, Struct, root_table, read_list, read_bytes, read_strings,\n"
            << "                  read_tables, read_structs, enum_value as _enum)\n"
            << extraImports(services);
        for (const std::string& dep : deps_)
            out << "import " << dep << "_bufs as " << dep << "\n";
        out << "\n\n" << body.str();
        return out.str();
    }

protected:
    // Hooks for programs that add to the output (librpc's rpcc: the clients of rpc_services).
    virtual void emitService(std::ostream&, const ServiceDef&) {}
    virtual std::string extraImports(bool /*services*/) { return ""; }
    virtual std::string runtimeModule() { return options_.runtime.empty() ? "bufs" : options_.runtime; }

    // ---- names --------------------------------------------------------------------------------------------

    static std::string pyName(const std::string& name) {
        static const std::set<std::string> reserved = {
            "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif",
            "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or",
            "pass", "raise", "return", "try", "while", "with", "yield", "match", "case", "type", "self", "cls", "init", "mb"};
        return reserved.count(name) ? name + "_" : name;
    }

    static std::string hex32(uint32_t v) {
        char buf[16];
        std::snprintf(buf, sizeof buf, "0x%08x", v);
        return buf;
    }

    std::string prefixFor(const Definition& def) {
        if (inMainFile(schema_, def))
            return "";
        const std::string stem = stemOf(def.file);
        deps_.insert(stem);
        return stem + ".";
    }

    std::string typeName(const Definition& def) { return prefixFor(def) + def.name; }

    // ---- scalars ------------------------------------------------------------------------------------------

    struct Scalar {
        const char* kind;  // Table getter / MessageBuilder setter suffix
        char fmt;          // struct format character
        uint32_t bytes;
        bool isSigned;
    };

    static Scalar scalar(Base base) {
        switch (base) {
        case Base::Bool: return {"u8", '?', 1, false};
        case Base::Int8: return {"i8", 'b', 1, true};
        case Base::UInt8: return {"u8", 'B', 1, false};
        case Base::Int16: return {"i16", 'h', 2, true};
        case Base::UInt16: return {"u16", 'H', 2, false};
        case Base::Int32: return {"i32", 'i', 4, true};
        case Base::UInt32: return {"u32", 'I', 4, false};
        case Base::Int64: return {"i64", 'q', 8, true};
        case Base::UInt64: return {"u64", 'Q', 8, false};
        case Base::Float32: return {"f32", 'f', 4, true};
        case Base::Float64: return {"f64", 'd', 8, true};
        default: break;
        }
        return {"u8", 'B', 1, false};
    }

    static Base storage(const Type& t) { return t.base == Base::Enum ? t.enumDef->underlying : t.base; }

    static uint32_t structFieldBytes(const Type& t) {
        if (t.base == Base::Struct)
            return t.structDef->size;
        return scalar(storage(t)).bytes;
    }

    static uint32_t elementBytes(const Type& t) {
        if (t.base == Base::String || t.base == Base::Table)
            return 4;
        return structFieldBytes(t);
    }

    static uint32_t elementAlign(const Type& t) {
        if (t.base == Base::String || t.base == Base::Table)
            return 4;
        if (t.base == Base::Struct)
            return t.structDef->align >= 8 ? 8 : 4;
        return structFieldBytes(t) >= 8 ? 8 : 4;
    }

    // The default as the integer the runtime XORs with: the value, or for floats its bit pattern.
    std::string defaultLiteral(const Field& f) {
        const Type& t = f.type;
        const std::string& d = f.defaultText;
        if (t.base == Base::Bool)
            return d == "true" || d == "1" ? "1" : "0";
        if (t.base == Base::Enum) {
            if (d.empty())
                return "0";
            for (const auto& [name, value] : t.enumDef->values)
                if (name == d)
                    return std::to_string(value);
            return "0";
        }
        if (isFloat(t.base)) {
            if (d.empty())
                return "0";
            const bool nan = d == "nan", inf = d == "inf" || d == "+inf", ninf = d == "-inf";
            if (t.base == Base::Float32) {
                float v = nan ? std::nanf("") : inf ? INFINITY : ninf ? -INFINITY : std::strtof(d.c_str(), nullptr);
                uint32_t bits;
                std::memcpy(&bits, &v, 4);
                if (nan)
                    bits = 0x7fc00000u;
                return std::to_string(bits);
            }
            double v = nan ? std::nan("") : inf ? INFINITY : ninf ? -INFINITY : std::strtod(d.c_str(), nullptr);
            uint64_t bits;
            std::memcpy(&bits, &v, 8);
            if (nan)
                bits = 0x7ff8000000000000ull;
            return std::to_string(bits);
        }
        if (d.empty())
            return "0";
        if (t.base == Base::UInt64)
            return std::to_string(std::strtoull(d.c_str(), nullptr, 0));
        return std::to_string(std::strtoll(d.c_str(), nullptr, 0));
    }

    // ---- emit ---------------------------------------------------------------------------------------------

    void doc(std::ostream& out, const std::vector<std::string>& lines, const char* indent) {
        if (lines.empty())
            return;
        out << indent << "\"\"\"";
        for (size_t i = 0; i < lines.size(); ++i)
            out << (i ? std::string("\n") + indent : "") << lines[i];
        out << "\"\"\"\n";
    }

    void emitEnum(std::ostream& out, const EnumDef& e) {
        out << "class " << e.name << "(_IntEnum):\n";
        doc(out, e.doc, "    ");
        if (e.values.empty())
            out << "    pass\n";
        for (const auto& [name, value] : e.values)
            out << "    " << pyName(name) << " = " << value << "\n";
        out << "\n\n";
    }

    // Python expression for the zero value of a struct member.
    std::string zeroOf(const Type& t) {
        std::string one;
        if (t.base == Base::Struct)
            one = typeName(*t.structDef) + "()";
        else if (t.base == Base::Enum)
            one = "_enum(" + typeName(*t.enumDef) + ", 0)";
        else if (t.base == Base::Bool)
            one = "False";
        else if (isFloat(t.base))
            one = "0.0";
        else
            one = "0";
        if (t.fixedLength)
            return "[" + one + " for _ in range(" + std::to_string(t.fixedLength) + ")]";
        return one;
    }

    std::string readOne(const Type& t, const std::string& at) {
        if (t.base == Base::Struct)
            return typeName(*t.structDef) + "._read(buf, " + at + ")";
        const std::string read = std::string("_struct.unpack_from('<") + scalar(storage(t)).fmt + "', buf, " + at + ")[0]";
        return t.base == Base::Enum ? "_enum(" + typeName(*t.enumDef) + ", " + read + ")" : read;
    }

    std::string writeOne(const Type& t, const std::string& at, const std::string& value) {
        if (t.base == Base::Struct)
            return value + "._write(buf, " + at + ")";
        return std::string("_struct.pack_into('<") + scalar(storage(t)).fmt + "', buf, " + at + ", " + value + ")";
    }

    void emitStruct(std::ostream& out, const StructDef& s) {
        out << "class " << s.name << "(Struct):\n";
        doc(out, s.doc, "    ");
        out << "    SIZE = " << s.size << "\n    __slots__ = (";
        for (const Field& f : s.fields)
            out << "'" << pyName(f.name) << "', ";
        out << ")\n\n    def __init__(self";
        for (const Field& f : s.fields)
            out << ", " << pyName(f.name) << "=None";
        out << "):\n";
        for (const Field& f : s.fields)
            out << "        self." << pyName(f.name) << " = " << zeroOf(f.type) << " if " << pyName(f.name) << " is None else " << pyName(f.name) << "\n";
        if (s.fields.empty())
            out << "        pass\n";
        out << "\n    @classmethod\n    def _read(cls, buf, at):\n        return cls(";
        for (size_t i = 0; i < s.fields.size(); ++i) {
            const Field& f = s.fields[i];
            const uint32_t offset = f.bitOffset / 8;
            const std::string at = "at + " + std::to_string(offset);
            out << (i ? ", " : "") << pyName(f.name) << "=";
            if (f.type.fixedLength)
                out << "[" << readOne(f.type, at + " + i * " + std::to_string(structFieldBytes(f.type))) << " for i in range("
                    << f.type.fixedLength << ")]";
            else
                out << readOne(f.type, at);
        }
        out << ")\n\n    def _write(self, buf, at):\n";
        for (const Field& f : s.fields) {
            const std::string at = "at + " + std::to_string(f.bitOffset / 8);
            const std::string member = "self." + pyName(f.name);
            if (f.type.fixedLength)
                out << "        for i, item in enumerate(" << member << "[:" << f.type.fixedLength << "]):\n            "
                    << writeOne(f.type, at + " + i * " + std::to_string(structFieldBytes(f.type)), "item") << "\n";
            else
                out << "        " << writeOne(f.type, at, member) << "\n";
        }
        if (s.fields.empty())
            out << "        pass\n";
        out << "\n\n";
    }

    // The property that reads one table field.
    void emitGetter(std::ostream& out, const Field& f) {
        const Type& t = f.type;
        const std::string name = pyName(f.name);
        const std::string offset = std::to_string(f.bitOffset / 8);
        const std::string ref = std::to_string(f.refIndex);
        out << "    @property\n    def " << name << "(self):\n";
        doc(out, f.doc, "        ");
        if (t.vector) {
            if (t.base == Base::String) {
                out << "        return read_strings(self._t, " << ref << ")\n";
            } else if (t.base == Base::Table) {
                out << "        return [" << typeName(*t.tableDef) << "(t) for t in read_tables(self._t, " << ref << ")]\n";
            } else if (t.base == Base::UInt8) {
                out << "        return read_bytes(self._t, " << ref << ")\n";
            } else if (t.base == Base::Struct) {
                out << "        return read_structs(self._t, " << ref << ", " << t.structDef->size << ", " << typeName(*t.structDef) << "._read)\n";
            } else {
                const std::string list = std::string("read_list(self._t, ") + ref + ", '" + scalar(storage(t)).fmt + "', " +
                                         std::to_string(elementBytes(t)) + ")";
                if (t.base == Base::Enum)
                    out << "        return [_enum(" << typeName(*t.enumDef) << ", v) for v in " << list << "]\n";
                else
                    out << "        return " << list << "\n";
            }
            return;
        }
        switch (t.base) {
        case Base::String: out << "        return self._t.string(" << ref << ")\n"; return;
        case Base::Table:
            out << "        t = self._t.table(" << ref << ")\n        return " << typeName(*t.tableDef) << "(t) if t is not None else None\n";
            return;
        case Base::Struct:
            out << "        a = self._t.struct_at(" << offset << ", " << t.structDef->size << ")\n        return " << typeName(*t.structDef)
                << "() if a < 0 else " << typeName(*t.structDef) << "._read(self._t.buf, a)\n";
            return;
        case Base::Bool:
            out << "        return self._t.bit(" << offset << ", " << f.bitOffset % 8 << ", " << defaultLiteral(f) << ")\n";
            return;
        case Base::Enum:
            out << "        return _enum(" << typeName(*t.enumDef) << ", self._t." << scalar(storage(t)).kind << "(" << offset << ", "
                << defaultLiteral(f) << "))\n";
            return;
        default:
            out << "        return self._t." << scalar(t.base).kind << "(" << offset << ", " << defaultLiteral(f) << ")\n";
            return;
        }
    }

    // Statements that write init["name"] into table `t` of the message `mb`.
    void emitWriteField(std::ostream& out, const TableDef& table, const Field& f) {
        const Type& t = f.type;
        const std::string value = "v";
        out << "    v = init.get('" << f.name << "')\n    if v is not None:\n";
        if (t.vector) {
            const std::string ref = std::to_string(f.refIndex);
            if (t.base == Base::String) {
                out << "        vec = mb.vector(len(v), 4, 4)\n        for i, s in enumerate(v):\n            mb.set_element_ref(vec, i, mb.string(s))\n";
            } else if (t.base == Base::Table) {
                out << "        vec = mb.vector(len(v), 4, 4)\n        for i, item in enumerate(v):\n            mb.set_element_ref(vec, i, _write_"
                    << typeName(*t.tableDef) << "(mb, item))\n";
            } else if (t.base == Base::Struct) {
                out << "        vec = mb.vector(len(v), " << t.structDef->size << ", " << elementAlign(t) << ")\n        for i, item in enumerate(v):\n"
                    << "            item._write(mb.buf, vec + 4 + i * " << t.structDef->size << ")\n";
            } else if (t.base == Base::UInt8 || t.base == Base::Int8) {
                out << "        vec = mb.vector(len(v), 1, 4)\n        mb.pack_list('" << scalar(t.base).fmt << "', vec + 4, v)\n";
            } else {
                out << "        vec = mb.vector(len(v), " << elementBytes(t) << ", " << elementAlign(t) << ")\n        mb.pack_list('"
                    << scalar(storage(t)).fmt << "', vec + 4, v)\n";
            }
            out << "        mb.set_ref(t, " << table.dataBytes << ", " << ref << ", vec)\n";
            return;
        }
        switch (t.base) {
        case Base::String: out << "        mb.set_ref(t, " << table.dataBytes << ", " << f.refIndex << ", mb.string(v))\n"; break;
        case Base::Table:
            out << "        mb.set_ref(t, " << table.dataBytes << ", " << f.refIndex << ", _write_" << typeName(*t.tableDef) << "(mb, v))\n";
            break;
        case Base::Struct: out << "        v._write(mb.buf, t + " << f.bitOffset / 8 << ")\n"; break;
        case Base::Bool:
            out << "        mb.set_bit(t + " << f.bitOffset / 8 << ", " << f.bitOffset % 8 << ", v, " << defaultLiteral(f) << ")\n";
            break;
        default:
            out << "        mb.set_" << scalar(storage(t)).kind << "(t + " << f.bitOffset / 8 << ", v, " << defaultLiteral(f) << ")\n";
            break;
        }
    }

    void emitTable(std::ostream& out, const TableDef& table) {
        const std::string name = table.name;
        out << "class " << name << ":\n";
        doc(out, table.doc, "    ");
        out << "    TYPE_ID = " << hex32(typeIdOf(table.qualified())) << "\n    TYPE_NAME = '" << table.qualified() << "'\n"
            << "    __slots__ = ('_t',)\n\n    def __init__(self, table):\n        self._t = table\n\n"
            << "    @classmethod\n    def decode(cls, data):\n        \"\"\"Reads the root of a received message; raises MalformedMessage if it is not a " << table.qualified()
            << ".\"\"\"\n        return cls(root_table(data, cls.TYPE_ID, cls.TYPE_NAME))\n\n"
            << "    @staticmethod\n    def encode(init=None, **fields):\n        \"\"\"Builds a message from a dict or keyword arguments (a field left out keeps its default).\"\"\"\n"
            << "        mb = MessageBuilder(" << name << ".TYPE_ID)\n        _write_" << name << "(mb, init if init is not None else fields)\n        return mb.finish()\n\n";
        bool any = false;
        for (const Field& f : table.fields) {
            if (f.deprecated)
                continue;
            emitGetter(out, f);
            out << "\n";
            any = true;
        }
        out << "    def to_dict(self):\n        \"\"\"The fields as plain Python values (tables become dicts).\"\"\"\n        d = {}\n";
        for (const Field& f : table.fields) {
            if (f.deprecated)
                continue;
            const std::string n = pyName(f.name);
            std::string expr = "self." + n;
            if (f.type.base == Base::Table)
                expr = f.type.vector ? "[x.to_dict() for x in self." + n + "]" : "(self." + n + ".to_dict() if self." + n + " is not None else None)";
            out << "        d['" << f.name << "'] = " << expr << "\n";
        }
        out << "        return d\n\n    def __repr__(self):\n        return f'" << name << "({self.to_dict()})'\n";
        (void)any;
        out << "\n\ndef _write_" << name << "(mb, init):\n    t = mb.table(" << table.dataBytes << ", " << table.refCount << ")\n";
        for (const Field& f : table.fields)
            if (!f.deprecated)
                emitWriteField(out, table, f);
        out << "    return t\n\n\n";
    }

    const Schema& schema_;
    const GenOptions& options_;
    std::set<std::string> deps_;
};

} // namespace bufsc
