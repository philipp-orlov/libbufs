using namespace tsgen;

class TsGenerator {
public:
    TsGenerator(const Schema& schema, const GenOptions& options) : schema_(schema), options_(options) {}
    virtual ~TsGenerator() = default;

    std::string run() {
        std::ostringstream body;
        for (const auto& e : schema_.enums)
            if (inMainFile(schema_, *e))
                emitEnum(body, *e);
        for (const auto& s : schema_.structs)
            if (inMainFile(schema_, *s))
                emitStruct(body, *s);
        for (const auto& t : schema_.tables)
            if (inMainFile(schema_, *t))
                emitTable(body, *t);
        bool services = false;
        for (const auto& s : schema_.services)
            if (inMainFile(schema_, *s)) {
                emitService(body, *s);
                services = true;
            }

        std::ostringstream out;
        out << "// Generated by " << options_.generator << " from " << stemOf(schema_.mainFile) << ".bufs. Do not edit.\n"
            << "/* eslint-disable */\n"
            << "// prettier-ignore\n";
        out << "import {\n  Table,\n  MessageBuilder,\n  rootTable,\n  readList,\n  readBytes,\n  readStrings,\n  readTables,\n"
               "  readBigList,\n} from '"
            << runtimeModule() << "';\n"
            << extraImports(services);
        for (const std::string& dep : deps_)
            out << "import * as " << dep << " from './" << dep << ".bufs';\n";
        out << "\n" << body.str();
        return out.str();
    }

protected:
    // ---- names ------------------------------------------------------------------------------------------

    std::string prefixFor(const Definition& def) {
        if (inMainFile(schema_, def))
            return "";
        const std::string stem = stemOf(def.file);
        deps_.insert(stem);
        return stem + ".";
    }

    std::string typeName(const Definition& def) { return prefixFor(def) + def.name; }

    // The TypeScript type of one element of `t`.
    std::string elementType(const Type& t) {
        switch (t.base) {
        case Base::String: return "string";
        case Base::Enum: return typeName(*t.enumDef);
        case Base::Struct: return typeName(*t.structDef);
        case Base::Table: return typeName(*t.tableDef);
        default: return scalar(t.base).ts;
        }
    }

    std::string initElementType(const Type& t) {
        switch (t.base) {
        case Base::Table: return prefixFor(*t.tableDef) + t.tableDef->name + "Init";
        case Base::Int64:
        case Base::UInt64: return "bigint | number";
        default: return elementType(t);
        }
    }

    // What a caller passes for a field (or a natural-form parameter) of type `t`.
    std::string initFieldType(const Type& t) {
        std::string type = initElementType(t);
        if (!t.vector)
            return type;
        if (t.base == Base::UInt8 || t.base == Base::Int8)
            return "Uint8Array | number[]";
        if (type.find('|') != std::string::npos)
            return "(" + type + ")[]";
        return type + "[]";
    }

    // What a reader hands back for a field of type `t`.
    std::string readFieldType(const Type& t) {
        if (!t.vector)
            return elementType(t);
        if (t.base == Base::UInt8)
            return "Uint8Array";
        return elementType(t) + "[]";
    }

    static std::string paramName(const std::string& name) {
        static const std::set<std::string> reserved = {
            "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
            "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
            "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
            "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "options"};
        const std::string c = camel(name);
        return reserved.count(c) ? c + "_" : c;
    }

    // The default of a natural-form parameter as a TypeScript expression, or "" for none.
    std::string defaultExpr(const Field& f) {
        if (f.defaultText.empty() || f.type.vector)
            return {};
        switch (f.type.base) {
        case Base::Enum: return typeName(*f.type.enumDef) + "." + f.defaultText;
        case Base::Bool: return f.defaultText == "true" || f.defaultText == "1" ? "true" : "false";
        case Base::Int64:
        case Base::UInt64: return f.defaultText + "n";
        case Base::String:
        case Base::Struct:
        case Base::Table: return {};
        default:
            if (f.defaultText == "nan") return "NaN";
            if (f.defaultText == "inf") return "Infinity";
            if (f.defaultText == "-inf") return "-Infinity";
            return f.defaultText;
        }
    }

    static uint32_t structFieldBytes(const Type& t) {
        uint32_t one = 0;
        if (t.base == Base::Struct)
            one = t.structDef->size;
        else if (t.base == Base::Enum)
            one = scalar(t.enumDef->underlying).bytes;
        else
            one = scalar(t.base).bytes;
        return one;
    }

    static uint32_t elementBytes(const Type& t) {
        if (t.base == Base::String || t.base == Base::Table)
            return 4;
        return structFieldBytes(t);
    }

    static uint32_t elementAlign(const Type& t) {
        if (t.base == Base::String || t.base == Base::Table)
            return 4;
        if (t.base == Base::Struct)
            return t.structDef->align >= 8 ? 8 : 4;
        return structFieldBytes(t) >= 8 ? 8 : 4;
    }

    // ---- defaults ---------------------------------------------------------------------------------------

    std::string defaultLiteral(const Field& f) {
        const Type& t = f.type;
        const std::string& d = f.defaultText;
        if (t.base == Base::Bool)
            return d == "true" || d == "1" ? "1" : "0";
        if (t.base == Base::Enum) {
            if (d.empty())
                return "0";
            for (const auto& [name, value] : t.enumDef->values)
                if (name == d)
                    return std::to_string(value);
            return "0";
        }
        if (isFloat(t.base)) {
            if (d.empty())
                return t.base == Base::Float32 ? "0" : "0n";
            if (t.base == Base::Float32) {
                float v = d == "nan" ? std::nanf("") : (d == "inf" || d == "+inf") ? INFINITY : d == "-inf" ? -INFINITY
                                                                                              : std::strtof(d.c_str(), nullptr);
                uint32_t bits;
                std::memcpy(&bits, &v, 4);
                if (d == "nan")
                    bits = 0x7fc00000u;
                return std::to_string(bits);
            }
            double v = d == "nan" ? std::nan("") : (d == "inf" || d == "+inf") ? INFINITY : d == "-inf" ? -INFINITY
                                                                                           : std::strtod(d.c_str(), nullptr);
            uint64_t bits;
            std::memcpy(&bits, &v, 8);
            if (d == "nan")
                bits = 0x7ff8000000000000ull;
            return std::to_string(bits) + "n";
        }
        if (d.empty())
            return scalar(t.base).big ? "0n" : "0";
        if (t.base == Base::UInt64)
            return std::to_string(std::strtoull(d.c_str(), nullptr, 0)) + "n";
        if (t.base == Base::Int64)
            return std::to_string(std::strtoll(d.c_str(), nullptr, 0)) + "n";
        return std::to_string(std::strtoll(d.c_str(), nullptr, 0));
    }

    bool hasDefault(const Field& f) {
        const std::string d = defaultLiteral(f);
        return d != "0" && d != "0n";
    }

    // ---- struct members ---------------------------------------------------------------------------------

    // Expression reading one value of `t` (not a vector) at byte offset `at` of DataView `v`.
    std::string readExpr(const Type& t, const std::string& v, const std::string& at) {
        if (t.base == Base::Struct)
            return prefixFor(*t.structDef) + "read" + t.structDef->name + "(" + v + ", " + at + ")";
        const Base base = t.base == Base::Enum ? t.enumDef->underlying : t.base;
        const ScalarInfo info = scalar(base);
        std::string read = v + "." + info.get + "(" + at + (info.bytes > 1 ? ", true" : "") + ")";
        if (base == Base::Bool)
            read += " !== 0";
        return read;
    }

    std::string writeStmt(const Type& t, const std::string& v, const std::string& at, const std::string& value) {
        if (t.base == Base::Struct)
            return prefixFor(*t.structDef) + "write" + t.structDef->name + "(" + v + ", " + at + ", " + value + ");";
        const Base base = t.base == Base::Enum ? t.enumDef->underlying : t.base;
        const ScalarInfo info = scalar(base);
        std::string arg = value;
        if (base == Base::Bool)
            arg = "(" + value + " ? 1 : 0)";
        else if (info.big)
            arg = "BigInt(" + value + ")";
        return v + "." + info.set + "(" + at + ", " + arg + (info.bytes > 1 ? ", true" : "") + ");";
    }

    // ---- emit -------------------------------------------------------------------------------------------

    void doc(std::ostream& out, const std::vector<std::string>& lines, const char* indent) {
        if (lines.empty())
            return;
        out << indent << "/**\n";
        for (const std::string& line : lines)
            out << indent << " *" << (line.empty() ? "" : " ") << line << "\n";
        out << indent << " */\n";
    }

    void emitEnum(std::ostream& out, const EnumDef& e) {
        doc(out, e.doc, "");
        out << "export enum " << e.name << " {\n";
        for (const auto& [name, value] : e.values)
            out << "  " << name << " = " << value << ",\n";
        out << "}\n\n";
    }

    void emitStruct(std::ostream& out, const StructDef& s) {
        doc(out, s.doc, "");
        out << "export interface " << s.name << " {\n";
        for (const Field& f : s.fields) {
            const std::string element = elementType(f.type);
            const bool big = f.type.base == Base::Int64 || f.type.base == Base::UInt64;
            out << "  " << camel(f.name) << ": " << (f.type.fixedLength ? element + "[]" : element)
                << (big && false ? "" : "") << ";\n";
        }
        out << "}\n\nexport const " << s.name << "Size = " << s.size << ";\n\n";

        out << "export function read" << s.name << "(v: DataView, at: number): " << s.name << " {\n  return {\n";
        for (const Field& f : s.fields) {
            const uint32_t offset = f.bitOffset / 8;  // bitOffset counts bits here too
            const std::string at = "at + " + std::to_string(offset);
            if (f.type.fixedLength) {
                const uint32_t size = structFieldBytes(f.type);
                out << "    " << camel(f.name) << ": Array.from({ length: " << f.type.fixedLength << " }, (_, i) => "
                    << readExpr(f.type, "v", at + " + i * " + std::to_string(size)) << "),\n";
            } else {
                out << "    " << camel(f.name) << ": " << readExpr(f.type, "v", at) << ",\n";
            }
        }
        out << "  };\n}\n\n";

        out << "export function write" << s.name << "(v: DataView, at: number, s: " << s.name << "): void {\n";
        for (const Field& f : s.fields) {
            const std::string at = "at + " + std::to_string(f.bitOffset / 8);
            const std::string member = "s." + camel(f.name);
            if (f.type.fixedLength) {
                const uint32_t size = structFieldBytes(f.type);
                out << "  for (let i = 0; i < " << f.type.fixedLength << " && i < " << member << ".length; i++) {\n    "
                    << writeStmt(f.type, "v", at + " + i * " + std::to_string(size), member + "[i]") << "\n  }\n";
            } else {
                out << "  " << writeStmt(f.type, "v", at, member) << "\n";
            }
        }
        out << "}\n\nfunction zero" << s.name << "(): " << s.name << " {\n  return read" << s.name
            << "(new DataView(new ArrayBuffer(" << s.size << ")), 0);\n}\n\n";
    }

    // A getter's body for one table field.
    void emitGetter(std::ostream& out, const TableDef& table, const Field& f) {
        const Type& t = f.type;
        const std::string name = camel(f.name);
        const std::string offset = std::to_string(f.bitOffset / 8);
        doc(out, f.doc, "  ");
        if (t.vector) {
            const std::string ref = std::to_string(f.refIndex);
            if (t.base == Base::String) {
                out << "  get " << name << "(): string[] {\n    return readStrings(this.table.view, this.table.vector(" << ref << "));\n  }\n";
            } else if (t.base == Base::Table) {
                out << "  get " << name << "(): " << typeName(*t.tableDef) << "[] {\n    return readTables(this.table.view, this.table.vector(" << ref
                    << ")).map((t) => new " << typeName(*t.tableDef) << "(t));\n  }\n";
            } else if (t.base == Base::UInt8 || t.base == Base::Int8) {
                out << "  get " << name << "(): " << (t.base == Base::UInt8 ? "Uint8Array" : "number[]") << " {\n    "
                    << (t.base == Base::UInt8 ? "return readBytes(this.table.view, this.table.vector(" + ref + "));"
                                              : "return readList(this.table.view, this.table.vector(" + ref + "), 1, (v, a) => v.getInt8(a));")
                    << "\n  }\n";
            } else {
                const uint32_t size = elementBytes(t);
                const bool big = (t.base == Base::Int64 || t.base == Base::UInt64) ||
                                 (t.base == Base::Enum && scalar(t.enumDef->underlying).big);
                const std::string reader = readExpr(t, "v", "a");
                out << "  get " << name << "(): " << elementType(t) << "[] {\n    return " << (big ? "readBigList" : "readList")
                    << "(this.table.view, this.table.vector(" << ref << "), " << size << ", (v, a) => " << reader
                    << ")" << (t.base == Base::Enum ? " as " + elementType(t) + "[]" : "") << ";\n  }\n";
            }
            return;
        }
        switch (t.base) {
        case Base::String:
            out << "  get " << name << "(): string {\n    return this.table.string(" << f.refIndex << ");\n  }\n";
            return;
        case Base::Table:
            out << "  get " << name << "(): " << typeName(*t.tableDef) << " | null {\n    const t = this.table.table(" << f.refIndex
                << ");\n    return t ? new " << typeName(*t.tableDef) << "(t) : null;\n  }\n";
            return;
        case Base::Struct: {
            const std::string sname = typeName(*t.structDef);
            const std::string prefix = prefixFor(*t.structDef);
            out << "  get " << name << "(): " << sname << " {\n    const a = this.table.structAt(" << offset << ", " << t.structDef->size
                << ");\n    return a < 0 ? " << prefix << "zero" << t.structDef->name << "() : " << prefix << "read" << t.structDef->name
                << "(this.table.view, a);\n  }\n";
            return;
        }
        case Base::Bool:
            out << "  get " << name << "(): boolean {\n    return this.table.bit(" << offset << ", " << f.bitOffset % 8 << ", "
                << defaultLiteral(f) << ");\n  }\n";
            return;
        case Base::Enum: {
            const ScalarInfo info = scalar(t.enumDef->underlying);
            out << "  get " << name << "(): " << typeName(*t.enumDef) << " {\n    return this.table." << info.table << "(" << offset << ", "
                << defaultLiteral(f) << ") as " << typeName(*t.enumDef) << ";\n  }\n";
            return;
        }
        default: {
            const ScalarInfo info = scalar(t.base);
            out << "  get " << name << "(): " << info.ts << " {\n    return this.table." << info.table << "(" << offset << ", "
                << defaultLiteral(f) << ");\n  }\n";
            return;
        }
        }
        (void)table;
    }

    // Statements that write one init value into table `t` (a local) of the message `mb`.
    void emitWriteField(std::ostream& out, const TableDef& table, const Field& f) {
        const Type& t = f.type;
        const std::string name = camel(f.name);
        const std::string value = "init." + name;
        const std::string tableData = std::to_string(table.dataBytes);
        out << "  if (" << value << " !== undefined) {\n";
        if (t.vector) {
            const std::string ref = std::to_string(f.refIndex);
            const std::string size = std::to_string(elementBytes(t));
            const std::string align = std::to_string(elementAlign(t));
            if (t.base == Base::String) {
                out << "    const vector = mb.vector(" << value << ".length, 4, 4);\n"
                    << "    for (let i = 0; i < " << value << ".length; i++) mb.setElementRef(vector, i, mb.string(" << value << "[i]));\n";
            } else if (t.base == Base::Table) {
                out << "    const vector = mb.vector(" << value << ".length, 4, 4);\n"
                    << "    for (let i = 0; i < " << value << ".length; i++) mb.setElementRef(vector, i, " << prefixFor(*t.tableDef) << "write"
                    << t.tableDef->name << "(mb, " << value << "[i]));\n";
            } else if (t.base == Base::UInt8 || t.base == Base::Int8) {
                out << "    const vector = mb.vector(" << value << ".length, 1, 4);\n"
                    << "    for (let i = 0; i < " << value << ".length; i++) mb.view." << scalar(t.base).set << "(vector + 4 + i, " << value
                    << "[i]);\n";
            } else {
                out << "    const vector = mb.vector(" << value << ".length, " << size << ", " << align << ");\n"
                    << "    for (let i = 0; i < " << value << ".length; i++) {\n      "
                    << writeStmt(t, "mb.view", "vector + 4 + i * " + size, value + "[i]") << "\n    }\n";
            }
            out << "    mb.setRef(t, " << tableData << ", " << ref << ", vector);\n";
        } else {
            switch (t.base) {
            case Base::String:
                out << "    mb.setRef(t, " << tableData << ", " << f.refIndex << ", mb.string(" << value << "));\n";
                break;
            case Base::Table:
                out << "    mb.setRef(t, " << tableData << ", " << f.refIndex << ", " << prefixFor(*t.tableDef) << "write" << t.tableDef->name
                    << "(mb, " << value << "));\n";
                break;
            case Base::Struct:
                out << "    " << writeStmt(t, "mb.view", "t + " + std::to_string(f.bitOffset / 8), value) << "\n";
                break;
            case Base::Bool:
                out << "    mb.setBit(t + " << f.bitOffset / 8 << ", " << f.bitOffset % 8 << ", " << value << ", " << defaultLiteral(f)
                    << ");\n";
                break;
            default: {
                const Base base = t.base == Base::Enum ? t.enumDef->underlying : t.base;
                const ScalarInfo info = scalar(base);
                out << "    mb." << info.setter << "(t + " << f.bitOffset / 8 << ", " << value << ", " << defaultLiteral(f) << ");\n";
                break;
            }
            }
        }
        out << "  }\n";
    }

    void emitTable(std::ostream& out, const TableDef& table) {
        const std::string name = table.name;
        out << "export interface " << name << "Init {\n";
        for (const Field& f : table.fields) {
            if (f.deprecated)
                continue;
            doc(out, f.doc, "  ");
            const std::string type = initFieldType(f.type);
            out << "  " << camel(f.name) << "?: " << type << ";\n";
        }
        out << "}\n\n";

        doc(out, table.doc, "");
        out << "export class " << name << " {\n"
            << "  static readonly typeId = " << hex32(typeIdOf(table.qualified())) << ";\n"
            << "  static readonly typeName = '" << table.qualified() << "';\n\n"
            << "  constructor(readonly table: Table) {}\n\n"
            << "  /** Reads the root of a received message; throws if it is not a " << table.qualified() << ". */\n"
            << "  static decode(data: ArrayBuffer | ArrayBufferView): " << name << " {\n"
            << "    return new " << name << "(rootTable(data, " << name << ".typeId, " << name << ".typeName));\n  }\n\n"
            << "  /** Builds a message. */\n"
            << "  static encode(init: " << name << "Init): Uint8Array {\n"
            << "    const mb = new MessageBuilder(" << name << ".typeId);\n    write" << name << "(mb, init);\n    return mb.finish();\n  }\n\n";
        for (const Field& f : table.fields) {
            if (f.deprecated)
                continue;
            emitGetter(out, table, f);
            out << "\n";
        }
        out << "}\n\n";

        out << "/** Writes `init` as a table of the message being built; returns the table's offset. */\n"
            << "export function write" << name << "(mb: MessageBuilder, init: " << name << "Init): number {\n"
            << "  const t = mb.table(" << table.dataBytes << ", " << table.refCount << ");\n";
        for (const Field& f : table.fields)
            if (!f.deprecated)
                emitWriteField(out, table, f);
        out << "  return t;\n}\n\n";
    }


    // Hooks for programs that add to the output (librpc's rpcc: the clients of rpc_services).
    virtual void emitService(std::ostream&, const ServiceDef&) {}
    virtual std::string extraImports(bool /*services*/) { return ""; }
    virtual std::string runtimeModule() { return options_.runtime.empty() ? "@bufs/runtime" : options_.runtime; }

    const Schema& schema_;
    const GenOptions& options_;
    std::set<std::string> deps_;
};

