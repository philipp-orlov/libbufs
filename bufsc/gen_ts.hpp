struct ScalarInfo {
    const char* ts;       // TypeScript type
    const char* get;      // DataView getter
    const char* set;      // DataView setter
    const char* table;    // Table method name
    const char* setter;   // MessageBuilder method name
    uint32_t bytes;
    bool big;
};

inline ScalarInfo scalar(Base base) {
    switch (base) {
    case Base::Bool: return {"boolean", "getUint8", "setUint8", "bit", "setBit", 1, false};
    case Base::Int8: return {"number", "getInt8", "setInt8", "i8", "setI8", 1, false};
    case Base::UInt8: return {"number", "getUint8", "setUint8", "u8", "setU8", 1, false};
    case Base::Int16: return {"number", "getInt16", "setInt16", "i16", "setI16", 2, false};
    case Base::UInt16: return {"number", "getUint16", "setUint16", "u16", "setU16", 2, false};
    case Base::Int32: return {"number", "getInt32", "setInt32", "i32", "setI32", 4, false};
    case Base::UInt32: return {"number", "getUint32", "setUint32", "u32", "setU32", 4, false};
    case Base::Int64: return {"bigint", "getBigInt64", "setBigInt64", "i64", "setI64", 8, true};
    case Base::UInt64: return {"bigint", "getBigUint64", "setBigUint64", "u64", "setU64", 8, true};
    case Base::Float32: return {"number", "getFloat32", "setFloat32", "f32", "setF32", 4, false};
    case Base::Float64: return {"number", "getFloat64", "setFloat64", "f64", "setF64", 8, false};
    default: break;
    }
    return {"number", "getUint8", "setUint8", "u8", "setU8", 1, false};
}

inline std::string camel(const std::string& name) {
    std::string out;
    bool upper = false;
    for (char c : name) {
        if (c == '_') {
            upper = !out.empty();
            continue;
        }
        out += upper ? static_cast<char>(std::toupper(static_cast<unsigned char>(c))) : c;
        upper = false;
    }
    if (!out.empty())
        out[0] = static_cast<char>(std::tolower(static_cast<unsigned char>(out[0])));
    return out;
}


inline std::string hex32(uint32_t v) {
    char text[16];
    std::snprintf(text, sizeof text, "0x%08x", v);
    return text;
}


