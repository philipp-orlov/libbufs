#pragma once

// What the language generators of bufsc share. A generator writes the messages of a schema's main file (enums, structs,
// tables); a program that has more to say about the schema -- librpc's rpcc writes service clients -- derives from the
// generator and overrides emitService() and the import hooks.

#include <string>

#include "schema.hpp"

namespace bufsc {

struct GenOptions {
    std::string outDir = ".";
    // The module (TypeScript) or namespace (C#, Python) the generated code takes the bufs runtime from; empty: the default.
    std::string runtime;
    // Who is credited in the "Generated by" line.
    std::string generator = "bufsc";
};

inline bool inMainFile(const Schema& schema, const Definition& def) { return def.file == schema.mainFile; }

inline std::string stemOf(const std::string& path) {
    const size_t slash = path.find_last_of("/\\");
    std::string name = slash == std::string::npos ? path : path.substr(slash + 1);
    const size_t dot = name.rfind('.');
    return dot == std::string::npos ? name : name.substr(0, dot);
}

void writeFile(const std::string& path, const std::string& text);

// Write <stem>.bufs.ts / <stem>.bufs.cs / <stem>_bufs.py (messages only) into options.outDir. Return the path written.
std::string generateTypeScript(const Schema& schema, const GenOptions& options);
std::string generateCSharp(const Schema& schema, const GenOptions& options);
std::string generatePython(const Schema& schema, const GenOptions& options);

} // namespace bufsc
